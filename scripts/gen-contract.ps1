export type GlobalHealthKind = $($globalHealthMembers -join ' | ');
export type TrayStatusKind =
  $($trayStatusMembers -join ' | ');
export type ThemeKind = $($themeMembers -join ' | ');
export type SeverityKind = $($severityMembers -join ' | ');
export type TransportKind = $($transportMembers -join ' | ');
export type DeviceStateKind =
  | $($deviceStateMembers -join "`n  | ");
export type PairingPhase = $($pairingPhaseMembers -join ' | ');
export type SubsystemKind = $($subsystemMembers -join ' | ');

export interface AppSnapshot {
