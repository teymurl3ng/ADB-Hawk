# Regenerate ui/src/contract/snapshot.ts and actions.ts from the C# records and fail if the
# committed output drifts (ENGINEERING.md 4.2).
[CmdletBinding()]
param(
    [switch]$Verify
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot

$contractDir = Join-Path $repo 'ui\src\contract'
if (-not (Test-Path $contractDir)) {
    New-Item -ItemType Directory -Path $contractDir -Force | Out-Null
}

$snapshotFile = Join-Path $contractDir 'snapshot.ts'
$actionsFile = Join-Path $contractDir 'actions.ts'

$appSnapshotCs = Join-Path $repo 'src\AdbView\State\AppSnapshot.cs'
if (-not (Test-Path $appSnapshotCs)) {
    throw "C# contract file not found: $appSnapshotCs"
}
$appSnapshotText = [System.IO.File]::ReadAllText($appSnapshotCs)

function Get-EnumMembers([string]$text, [string]$enumName) {
    if ($text -match "enum\s+$enumName\s*\{([^}]+)\}") {
        $body = $matches[1]
        $members = @()
        foreach ($line in ($body -split "[\r\n,]")) {
            $trimmed = $line.Trim()
            if (-not $trimmed -or $trimmed.StartsWith("//") -or $trimmed.StartsWith("[")) {
                continue
            }
            $clean = ($trimmed -replace "\[.*?\]", "" -replace "//.*", "").Trim()
            if ($clean) {
                if ($clean -eq "WiFi") {
                    $members += "'wifi'"
                } else {
                    $members += "'" + $clean.Substring(0, 1).ToLowerInvariant() + $clean.Substring(1) + "'"
                }
            }
        }
        return $members
    }
    throw "Enum $enumName not found in $appSnapshotCs"
}

$globalHealthMembers = Get-EnumMembers $appSnapshotText 'GlobalHealthKind'
$trayStatusMembers = Get-EnumMembers $appSnapshotText 'TrayStatusKind'
$themeMembers = Get-EnumMembers $appSnapshotText 'ThemeKind'
$severityMembers = Get-EnumMembers $appSnapshotText 'SeverityKind'
$transportMembers = Get-EnumMembers $appSnapshotText 'TransportKind'
$deviceStateMembers = Get-EnumMembers $appSnapshotText 'DeviceStateKind'
$pairingPhaseMembers = Get-EnumMembers $appSnapshotText 'PairingPhase'
$subsystemMembers = Get-EnumMembers $appSnapshotText 'SubsystemKind'

$snapshotContent = @"
