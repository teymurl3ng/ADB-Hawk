"@

$actionsContent = @"
/* DO NOT EDIT MANUALLY. Generated by scripts/gen-contract.ps1 */

export type WebAction =
  | { type: 'ready'; protocol: number }
  | { type: 'pin' }
  | { type: 'unpin' }
  | { type: 'requestDismiss' }
  | {
      type: 'reportContentSize';
      heightEffectivePx: number;
      phase?: 'live' | 'structural' | 'reconcile';
      layoutKey?: string;
    }
  | { type: 'pairStart'; offerId: string }
  | { type: 'pairSubmit'; offerId: string; code: string }
  | { type: 'pairCancel'; offerId: string }
  | { type: 'discoveryRecheck' }
  | { type: 'discoveryRepair'; id: string }
  | { type: 'pairQrStart' }
  | { type: 'pairQrCancel' };
"@

# Normalize LF
$snapshotContent = ($snapshotContent.Trim() + "`n") -replace "`r`n", "`n"
$actionsContent = ($actionsContent.Trim() + "`n") -replace "`r`n", "`n"

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function Check-Or-Write([string]$path, [string]$content, [bool]$verifyMode) {
    if (Test-Path $path) {
        $existing = [System.IO.File]::ReadAllText($path) -replace "`r`n", "`n"
        if ($existing -eq $content) {
            Write-Host "gen-contract: up-to-date $(Split-Path -Leaf $path)"
            return
        }
        if ($verifyMode) {
            throw "Contract drift detected: $path differs from generated contract."
        }
    } elseif ($verifyMode) {
        throw "Contract drift detected: $path is missing."
    }

    [System.IO.File]::WriteAllText($path, $content, $utf8NoBom)
    Write-Host "gen-contract: generated $(Split-Path -Leaf $path)"
}

Check-Or-Write $snapshotFile $snapshotContent $Verify
Check-Or-Write $actionsFile $actionsContent $Verify
